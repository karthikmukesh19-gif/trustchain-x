REQUIREMENTS = """\
# web
requests>=2.31,<3
Flask==3.0.0  # pinned
uvicorn[standard]==0.30.1 ; python_version >= "3.9"
Django
pywin32==306; sys_platform == 'win32'
cryptography==42.0.5 \\
    --hash=sha256:aaaa1111 \\
    --hash=sha256:bbbb2222
-e git+https://user:secret@github.com/org/tool.git@v1#egg=tool
internal @ https://files.example.com/internal-1.0.tar.gz
--index-url https://token:pw@pypi.example.com/simple
-r dev.txt
-r ../../../etc/passwd
-c constraints.txt
./local/package
"""


def test_requirements_extracts_names_constraints_and_exact_versions():
    parsed = python.parse_requirements("backend/requirements.txt", REQUIREMENTS)
    deps = by_name(parsed.declared)
    assert parsed.kind == MANIFEST and parsed.ecosystem == "pypi"
    assert set(deps) == {"requests", "Flask", "uvicorn", "Django", "pywin32", "cryptography", "tool", "internal"}
    assert deps["requests"].constraint in {"<3,>=2.31", ">=2.31,<3"} and deps["requests"].exact_version is None
    assert deps["Flask"].exact_version == "3.0.0" and deps["Flask"].line == 3
    assert deps["uvicorn"].extras == ("standard",) and "python_version" in deps["uvicorn"].marker
    assert deps["Django"].constraint is None and deps["Django"].exact_version is None
    assert deps["cryptography"].integrity == [
        {"algorithm": "sha256", "value": "aaaa1111"}, {"algorithm": "sha256", "value": "bbbb2222"}]
    assert deps["cryptography"].line == 7


def test_requirements_never_invents_a_version():
    parsed = python.parse_requirements("requirements.txt", "requests\nflask>=2\nnumpy~=1.26\npandas==2.*\n")
    assert all(d.exact_version is None for d in parsed.declared)


def test_requirements_direct_classification_is_inferred_not_observed():
    dep = python.parse_requirements("requirements.txt", "requests==2.31.0\n").declared[0]
    assert (dep.relationship, dep.basis) == (DIRECT, INFERRED)
    assert "transitive" in dep.reason


def test_requirements_redacts_credentials_and_records_sources():
    parsed = python.parse_requirements("requirements.txt", REQUIREMENTS)
    deps = by_name(parsed.declared)
    assert deps["tool"].source["type"] == "git" and "secret" not in deps["tool"].source["location"]
    assert deps["internal"].source == {"type": "url", "location": "https://files.example.com/internal-1.0.tar.gz"}
    assert not any("pw@" in note or "secret" in note for note in parsed.notes)
    assert any("--index-url" in note and "never contacted" in note for note in parsed.notes)


def test_requirements_includes_cannot_escape_the_repository():
    parsed = python.parse_requirements("backend/requirements.txt", REQUIREMENTS)
    assert parsed.includes == ["backend/dev.txt"]
    assert any("etc/passwd" in note and "ignored" in note for note in parsed.notes)


