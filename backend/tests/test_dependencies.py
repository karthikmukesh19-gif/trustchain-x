def test_pipfile_and_lock():
    pipfile = python.parse_pipfile("Pipfile", '[packages]\nflask = "*"\nrequests = "==2.31.0"\n[dev-packages]\npytest = ">=8"\n')
    deps = by_name(pipfile.declared)
    assert deps["flask"].constraint == "*" and deps["flask"].exact_version is None
    assert deps["requests"].exact_version == "2.31.0" and deps["pytest"].scope == "dev"

    lock = python.parse_pipfile_lock("Pipfile.lock", json.dumps({
        "default": {"flask": {"version": "==3.0.0", "hashes": ["sha256:abc"]}, "click": {"version": "==8.1.7"},
                    "vcs": {"git": "https://github.com/a/b.git", "ref": "main"}},
        "develop": {"pytest": {"version": "==8.0.0"}}}))
    locked = by_name(lock.locked)
    assert locked["flask"].version == "3.0.0" and locked["flask"].integrity == [{"algorithm": "sha256", "value": "abc"}]
    assert locked["pytest"].dev is True and locked["click"].dev is False
    assert locked["vcs"].version is None                      # no version in the lock: not invented
    assert all(item.direct is None for item in lock.locked)   # Pipfile.lock does not say what is direct
    assert lock.records_edges is False


def test_poetry_lock_records_edges_but_not_roots():
    text = """\
[[package]]
name = "flask"
version = "3.0.0"
optional = false
groups = ["main"]
files = [{file = "flask.whl", hash = "sha256:f1"}]

[package.dependencies]
click = ">=8.1.3"
Werkzeug = ">=3.0.0"

[[package]]
name = "click"
version = "8.1.7"
groups = ["main"]

[[package]]
name = "werkzeug"
version = "3.0.1"
groups = ["dev"]
"""
    parsed = python.parse_poetry_lock("poetry.lock", text)
    locked = by_name(parsed.locked)
    assert parsed.records_edges and not parsed.records_roots
    assert {d[2] for d in locked["flask"].deps} == {"click@8.1.7", "werkzeug@3.0.1"}   # name normalised to match
    assert locked["flask"].integrity == [{"algorithm": "sha256", "value": "f1"}]
    assert locked["werkzeug"].dev is True and locked["flask"].direct is None


