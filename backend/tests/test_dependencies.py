def test_pip_compile_output_is_a_lockfile_with_observed_parents():
    text = """\
#
# This file is autogenerated by pip-compile
#
click==8.1.7
    # via flask
flask==3.0.0
    # via -r requirements.in
itsdangerous==2.1.2
    # via
    #   flask
    #   -r requirements.in
werkzeug==3.0.1  # via flask
orphan==1.0
"""
    parsed = python.parse_requirements("requirements.txt", text)
    locked = by_name(parsed.locked)
    assert parsed.kind == LOCKFILE and parsed.package_manager == "pip-compile" and parsed.records_edges
    assert locked["flask"].direct is True and locked["itsdangerous"].direct is True
    assert locked["click"].direct is False and locked["werkzeug"].direct is False
    assert locked["orphan"].direct is None          # no annotation: the file does not say
    assert {d[0] for d in locked["flask"].deps} == {"click", "itsdangerous", "werkzeug"}


