PACKAGE_LOCK_V3 = json.dumps({
    "name": "demo", "lockfileVersion": 3,
    "packages": {
        "": {"name": "demo", "dependencies": {"a": "^1.0.0"}, "devDependencies": {"d": "^1.0.0"}},
        "node_modules/a": {"version": "1.2.0", "resolved": "https://registry.npmjs.org/a/-/a-1.2.0.tgz",
                           "integrity": "sha512-AAAA", "dependencies": {"b": "^2.0.0", "c": "^1.0.0"},
                           "peerDependencies": {"missing-peer": "*"}},
        "node_modules/b": {"version": "2.5.0", "dependencies": {"c": "^2.0.0"}},
        "node_modules/b/node_modules/c": {"version": "2.0.1"},
        "node_modules/c": {"version": "1.9.0"},
        "node_modules/d": {"version": "1.0.0", "dev": True},
        "node_modules/@scope/e": {"version": "3.0.0", "optional": True},
        "node_modules/linked": {"resolved": "packages/linked", "link": True},
        "packages/linked": {"name": "linked", "version": "0.0.1", "dependencies": {"@scope/e": "^3.0.0"}},
    },
})


def test_package_lock_v3_roots_edges_and_nested_resolution():
    parsed = javascript.parse_package_lock("package-lock.json", PACKAGE_LOCK_V3)
    locked = {item.key: item for item in parsed.locked}
    assert parsed.records_roots and parsed.records_edges
    assert locked[""].local and locked["packages/linked"].local and "node_modules/linked" not in locked
    assert locked["node_modules/a"].direct is True and locked["node_modules/d"].direct is True
    assert locked["node_modules/b"].direct is False and locked["node_modules/c"].direct is False
    assert locked["node_modules/@scope/e"].direct is True and locked["node_modules/@scope/e"].name == "@scope/e"
    # "b" requires c@^2 and gets its own nested copy; "a" gets the hoisted c@1.9.0.
    assert ("c", "^2.0.0", "node_modules/b/node_modules/c") in locked["node_modules/b"].deps
    assert ("c", "^1.0.0", "node_modules/c") in locked["node_modules/a"].deps
    assert not any(d[0] == "missing-peer" for d in locked["node_modules/a"].deps)   # absent peer is not an edge
    assert locked["node_modules/a"].integrity == [{"algorithm": "sha512", "value": "AAAA"}]
    assert locked["node_modules/d"].dev is True and locked["node_modules/@scope/e"].optional is True


def test_package_lock_v1_does_not_claim_to_know_roots():
    text = json.dumps({"lockfileVersion": 1, "dependencies": {
        "a": {"version": "1.0.0", "requires": {"b": "^1.0.0"}, "dependencies": {"b": {"version": "1.5.0"}}},
        "b": {"version": "2.0.0", "dev": True}}})
    parsed = javascript.parse_package_lock("package-lock.json", text)
    locked = {item.key: item for item in parsed.locked}
    assert not parsed.records_roots
    assert all(item.direct is None for item in parsed.locked)
    assert locked["node_modules/a"].deps == [("b", "^1.0.0", "node_modules/a/node_modules/b")]


